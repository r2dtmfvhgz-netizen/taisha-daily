SENT_LOG = Path(__file__).parent / ".sent_dates.log"
# ================================


def get_today_key():
    """返回今天的日期字符串，作为去重键"""
    return datetime.now().strftime("%Y-%m-%d")


def already_sent_today():
    """检查今天是否已经发送过"""
    if not SENT_LOG.exists():
        return False
    today = get_today_key()
    with open(SENT_LOG, "r") as f:
        return any(line.strip() == today for line in f)


def mark_sent_today():
    """记录今天已发送"""
    today = get_today_key()
    with open(SENT_LOG, "a") as f:
        f.write(today + "\n")


